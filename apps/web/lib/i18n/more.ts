export function cityLabel(city: string | null | undefined, lang: Lang): string {
  if (!city) return "";
  const c = CITIES.find((x) => x.en.toLowerCase() === city.toLowerCase());
  return (c && lang !== "en" && c.alt[lang]) || city;
}

export function matchCity(text: string): string | null {
  const s = text.toLowerCase().replace(/[।॥.,!?;:]/g, " ").trim();
  if (!s) return null;
  let best: { en: string; len: number } | null = null;
  for (const c of CITIES) {
    const names = [c.en.toLowerCase(), ...Object.values(c.alt).map((x) => (x ?? "").toLowerCase()), ...(c.also ?? [])];
    for (const n of names) if (n && s.includes(n) && (!best || n.length > best.len)) best = { en: c.en, len: n.length };
  }
  return best?.en ?? null;
}
